package api

import (
	"os"
	"path/filepath"
	"reflect"
	"testing"
)

func writeLimiterWalkFile(t *testing.T, root, relative, source string) {
	t.Helper()
	path := filepath.Join(root, filepath.FromSlash(relative))
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(source), 0o600); err != nil {
		t.Fatal(err)
	}
}

const limiterImportingSource = "package x\n\nimport _ \"" + limiterImportPath + "\"\n"

// A checkout that ran npm ci holds Go files under node_modules (flatted ships
// one); the limiter walk must pass over them, while a Go file the module
// really owns, a vendored copy, and a linked node_modules still fail.
func TestLimiterWalkIgnoresNodeModulesButNotModuleOrVendoredCode(t *testing.T) {
	root := t.TempDir()
	rootCmd := filepath.Join(root, "cmd", "ovumcy")
	writeLimiterWalkFile(t, root, "cmd/ovumcy/main.go", limiterImportingSource)
	writeLimiterWalkFile(t, root, "node_modules/flatted/golang/pkg/flatted/flatted.go", limiterImportingSource)
	writeLimiterWalkFile(t, root, "web/node_modules/dep/dep.go", limiterImportingSource)

	offenders, err := limiterOffendersOutsideCompositionRoot(root, rootCmd)
	if err != nil {
		t.Fatal(err)
	}
	if len(offenders) != 0 {
		t.Fatalf("node_modules must not be read as module code, got %v", offenders)
	}

	writeLimiterWalkFile(t, root, "internal/bad/bad.go", limiterImportingSource)
	writeLimiterWalkFile(t, root, "tools/nested/go.mod", "module example.com/nested\n")
	writeLimiterWalkFile(t, root, "tools/nested/nested.go", limiterImportingSource)
	writeLimiterWalkFile(t, root, "vendor/example.com/dep/dep.go", limiterImportingSource)
	offenders, err = limiterOffendersOutsideCompositionRoot(root, rootCmd)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		filepath.ToSlash(filepath.Join(root, "internal", "bad", "bad.go")),
		filepath.ToSlash(filepath.Join(root, "tools", "nested", "nested.go")),
		filepath.ToSlash(filepath.Join(root, "vendor", "example.com", "dep", "dep.go")),
	}
	if !reflect.DeepEqual(offenders, want) {
		t.Fatalf("module-owned and vendored limiter imports must stay offenders\n got %v\nwant %v", offenders, want)
	}
}

func TestLimiterWalkStillFailsOnALinkedNodeModules(t *testing.T) {
	root := t.TempDir()
	target := filepath.Join(t.TempDir(), "elsewhere")
	if err := os.MkdirAll(target, 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(target, filepath.Join(root, "node_modules")); err != nil {
		t.Skipf("cannot create a symlink on this host: %v", err)
	}
	offenders, err := limiterOffendersOutsideCompositionRoot(root, filepath.Join(root, "cmd", "ovumcy"))
	if err != nil {
		t.Fatal(err)
	}
	if len(offenders) != 1 {
		t.Fatalf("a linked node_modules must fail the walk, got %v", offenders)
	}
}
